"""Rule rendering (DB objects -> iptables-restore script) and execution against the host.

Design:
  * Only the dedicated chains HTI-INPUT / HTI-FORWARD are managed. They are loaded with
    `iptables-restore --noflush`, which atomically replaces those chains and leaves every
    other rule on the host (Docker, libvirt, fail2ban, ...) untouched.
  * Jumps into the managed chains are inserted once at the top of INPUT and of
    DOCKER-USER (if Docker is present, as Docker recommends) or FORWARD.
  * The iptables backend (nft / legacy) is auto-detected to match the host.
"""
import logging
import os
import subprocess

log = logging.getLogger("hti.firewall")

CHAIN_INPUT = "HTI-INPUT"
CHAIN_FORWARD = "HTI-FORWARD"
CHAINS = {"input": CHAIN_INPUT, "forward": CHAIN_FORWARD}
MULTIPORT_MAX = 15  # a range counts as two
TRUE = ("1", "true", "yes", "on")


class IptablesError(RuntimeError):
    pass


def _port_chunks(ports: list[str]) -> list[str]:
    chunks, cur, weight = [], [], 0
    for p in ports:
        w = 2 if "-" in p else 1
        if weight + w > MULTIPORT_MAX:
            chunks.append(cur)
            cur, weight = [], 0
        cur.append(p.replace("-", ":"))
        weight += w
    if cur:
        chunks.append(cur)
    return [",".join(c) for c in chunks]


def _proto_matches(svc: dict | None) -> list[list[str]]:
    if svc is None or svc["protocol"] == "any":
        return [[]]
    if svc["protocol"] == "icmp":
        return [["-p", "icmp"]]
    protos = ["tcp", "udp"] if svc["protocol"] == "tcp+udp" else [svc["protocol"]]
    ports = [p for p in svc["ports"].split(",") if p]
    out = []
    for proto in protos:
        if not ports:
            out.append(["-p", proto])
        for chunk in _port_chunks(ports):
            if "," in chunk:
                out.append(["-p", proto, "-m", "multiport", "--dports", chunk])
            else:
                out.append(["-p", proto, "--dport", chunk])
    return out


def render_rule(rule: dict, networks: dict, services: dict, warnings: list[str]) -> list[str]:
    chain = CHAINS[rule["chain"]]
    match: list[str] = []

    src = networks.get(rule["src_network_id"])
    if src:
        if src["interface"]:
            match += ["-i", src["interface"]]
        if src["cidr"]:
            match += ["-s", src["cidr"]]

    dst = networks.get(rule["dst_network_id"])
    if dst:
        if dst["interface"]:
            if rule["chain"] == "forward":
                match += ["-o", dst["interface"]]
            else:
                warnings.append(f"Rule '{rule['name']}': destination interface is ignored on input rules")
        if dst["cidr"]:
            match += ["-d", dst["cidr"]]

    comment = ["-m", "comment", "--comment", f'"hti:{rule["id"]} {rule["name"]}"']
    lines = []
    for proto in _proto_matches(services.get(rule["service_id"])):
        base = ["-A", chain, *match, *proto, *comment]
        if rule["log"]:
            prefix = f'"HTI-{rule["id"]}-{rule["action"][:3]} "'
            lines.append(" ".join([*base, "-j", "LOG", "--log-prefix", prefix]))
        lines.append(" ".join([*base, "-j", rule["action"]]))
    return lines


def render(networks: dict, services: dict, rules: list[dict], settings: dict) -> tuple[str, list[str]]:
    warnings: list[str] = []
    lines = ["# Generated by HTI Firewall Manager - managed chains only", "*filter"]
    lines += [f":{c} - [0:0]" for c in CHAINS.values()]

    if settings["allow_established"]:
        for c in CHAINS.values():
            lines.append(f"-A {c} -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT")
    if settings["input_default"] == "DROP":
        lines.append(f"-A {CHAIN_INPUT} -i lo -j ACCEPT")
        if not settings["allow_established"]:
            warnings.append("Input default is DROP without established/related: replies to outgoing traffic will be dropped")
        if not any(r["enabled"] and r["chain"] == "input" and r["action"] == "ACCEPT" for r in rules):
            warnings.append("Input default is DROP and no input ACCEPT rule exists: you will lose remote access")

    for rule in rules:
        if rule["enabled"]:
            lines += render_rule(rule, networks, services, warnings)

    lines.append(f"-A {CHAIN_INPUT} -j {settings['input_default']}")
    lines.append(f"-A {CHAIN_FORWARD} -j {settings['forward_default']}")
    lines += ["COMMIT", ""]
    return "\n".join(lines), warnings


def empty_script() -> str:
    return "\n".join(["*filter", *(f":{c} - [0:0]" for c in CHAINS.values()), "COMMIT", ""])


class Iptables:
    def __init__(self) -> None:
        self.dry_run = os.environ.get("DRY_RUN", "false").lower() in TRUE
        self.mode = "dry-run" if self.dry_run else self._detect(os.environ.get("IPTABLES_MODE", "auto"))

    @staticmethod
    def _detect(wanted: str) -> str:
        """Pick the backend the host actually uses (same heuristic as kube-proxy's iptables-wrapper)."""
        if wanted in ("nft", "legacy"):
            return wanted
        counts = {}
        for mode in ("nft", "legacy"):
            try:
                out = subprocess.run([f"iptables-{mode}-save"], capture_output=True, text=True, timeout=15).stdout
            except (OSError, subprocess.SubprocessError):
                out = ""
            counts[mode] = sum(1 for line in out.splitlines() if line.startswith("-A "))
        mode = "legacy" if counts["legacy"] > counts["nft"] else "nft"
        log.info("iptables backend auto-detected: %s (rules: %s)", mode, counts)
        return mode

    @property
    def cmd(self) -> str:
        return f"iptables-{self.mode}"

    def _run(self, args: list[str], stdin: str | None = None) -> str:
        if self.dry_run:
            return ""
        try:
            p = subprocess.run(args, input=stdin, capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.SubprocessError) as e:
            raise IptablesError(f"{args[0]}: {e}") from e
        if p.returncode != 0:
            raise IptablesError((p.stderr or p.stdout).strip() or f"{args[0]} exited with {p.returncode}")
        return p.stdout

    def _ok(self, args: list[str]) -> bool:
        if self.dry_run:
            return True
        return subprocess.run(args, capture_output=True, timeout=30).returncode == 0

    def test(self, script: str) -> None:
        self._run([f"{self.cmd}-restore", "--test", "--noflush", "-w", "5"], script)

    def restore(self, script: str) -> None:
        self._run([f"{self.cmd}-restore", "--noflush", "-w", "5"], script)
        self.ensure_hooks()

    def ensure_hooks(self) -> None:
        self._ensure_jump("INPUT", CHAIN_INPUT)
        if self._ok([self.cmd, "-w", "5", "-n", "-L", "DOCKER-USER"]):
            # Docker owns FORWARD; DOCKER-USER is evaluated first for all forwarded traffic.
            while not self.dry_run and self._ok([self.cmd, "-w", "5", "-C", "FORWARD", "-j", CHAIN_FORWARD]):
                self._run([self.cmd, "-w", "5", "-D", "FORWARD", "-j", CHAIN_FORWARD])
            self._ensure_jump("DOCKER-USER", CHAIN_FORWARD)
        else:
            self._ensure_jump("FORWARD", CHAIN_FORWARD)

    def _ensure_jump(self, parent: str, chain: str) -> None:
        if not self._ok([self.cmd, "-w", "5", "-C", parent, "-j", chain]):
            self._run([self.cmd, "-w", "5", "-I", parent, "1", "-j", chain])

    def snapshot(self) -> str:
        """Current content of the managed chains, as a restorable script (used for rollback)."""
        if self.dry_run:
            return empty_script()
        out = self._run([f"{self.cmd}-save", "-t", "filter"])
        prefixes = tuple(f"-A {c} " for c in CHAINS.values())
        rules = [line for line in out.splitlines() if line.startswith(prefixes)]
        return "\n".join(["*filter", *(f":{c} - [0:0]" for c in CHAINS.values()), *rules, "COMMIT", ""])

    def save_all(self) -> str:
        return self._run([f"{self.cmd}-save"])

    def listing(self) -> str:
        if self.dry_run:
            return "DRY_RUN is enabled: nothing is applied, no live counters."
        parts = []
        for chain in CHAINS.values():
            try:
                parts.append(self._run([self.cmd, "-w", "5", "-L", chain, "-n", "-v", "-x", "--line-numbers"]))
            except IptablesError as e:
                parts.append(f"{chain}: {e}\n")
        return "\n".join(parts)
